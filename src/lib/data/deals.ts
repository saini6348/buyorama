export function getDealsByStore(storeSlug: string): Deal[] {
  return deals
    .filter((d) => d.storeSlug === storeSlug)
    .sort((a, b) => new Date(b.publishedAt).getTime() - new Date(a.publishedAt).getTime());
}

export function getTrendingDeals(limit = 4): Deal[] {
  return [...deals]
    .sort((a, b) => new Date(b.publishedAt).getTime() - new Date(a.publishedAt).getTime())
    .slice(0, limit);
}
